"""Compare the metrics: does each one score meaning-preserving edits above breaking ones?

Headline: pairwise accuracy. For every scenario, every (harmless edit, breaking edit)
pair is a comparison the metric gets right if it scores the harmless edit higher
(a tie counts half). Comparing edits of the same scenario cancels out scenario
length and wording, so the number is about the metric, not the data. The 95%
interval comes from resampling scenarios.

Reads data/scores.csv and, if present, data/scores_bertscore.csv.

    python benchmark/analyse.py          # prints and writes benchmark/results.md
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

import numpy as np
from generate import BENIGN, BREAKING, EDITS

DATA = Path(__file__).parent / "data"
LABELS = {"gbleu": "G-BLEU", "word_bleu": "word BLEU", "sacrebleu": "sacreBLEU", "rouge_l": "ROUGE-L",
          "bertscore": "BERTScore (raw text)",
          "bertscore_trimmed": "BERTScore (lines trimmed)"}
RESAMPLES = 10_000


def load() -> tuple[dict, list[str]]:
    """scores[metric][scenario][edit] -> float"""
    scores: dict = defaultdict(lambda: defaultdict(dict))
    metrics = []
    for name in ("scores.csv", "scores_bertscore.csv"):
        path = DATA / name
        if not path.exists():
            continue
        with path.open(encoding="utf-8") as f:
            for row in csv.DictReader(f):
                for metric, value in row.items():
                    if metric in ("id", "edit"):
                        continue
                    scores[metric][row["id"]][row["edit"]] = float(value)
                    if metric not in metrics:
                        metrics.append(metric)
    return scores, metrics


def pairwise(per_scenario: dict, benign: list[str], breaking: list[str]) -> np.ndarray:
    """Per scenario: share of (benign, breaking) pairs where the benign edit scores higher."""
    out = []
    for edits in per_scenario.values():
        wins = [1.0 if edits[b] > edits[k] else 0.5 if edits[b] == edits[k] else 0.0 for b in benign for k in breaking]
        out.append(sum(wins) / len(wins))
    return np.array(out)


def interval(values: np.ndarray, seed: int = 0) -> tuple[float, float]:
    rng = np.random.default_rng(seed)
    means = values[rng.integers(0, len(values), size=(RESAMPLES, len(values)))].mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def main() -> None:
    scores, metrics = load()
    scenarios = len(next(iter(scores.values())))
    lines = [
        "# Benchmark results",
        "",
        f"{scenarios} scenarios, {len(EDITS)} edits each. Generated by `benchmark/generate.py`;"
        " scores in `benchmark/data/`.",
        "",
        "## Pairwise accuracy",
        "",
        "How often the metric scores a meaning-preserving edit above a meaning-breaking edit of the same"
        " scenario. 0.5 is a coin toss; 1.0 is perfect.",
        "",
        "| Metric | Pairwise accuracy | 95% interval |",
        "|---|---:|---|",
    ]
    for m in metrics:
        acc = pairwise(scores[m], BENIGN, BREAKING)
        low, high = interval(acc)
        lines.append(f"| {LABELS.get(m, m)} | {acc.mean():.3f} | {low:.3f} to {high:.3f} |")

    lines += ["", "### Which breaks each metric catches", "",
              "Accuracy against each breaking edit, over all three harmless edits.", "",
              "| Breaking edit | " + " | ".join(LABELS.get(m, m) for m in metrics) + " |",
              "|---|" + "---:|" * len(metrics)]
    for k in BREAKING:
        lines.append(f"| {k} | " + " | ".join(f"{pairwise(scores[m], BENIGN, [k]).mean():.3f}" for m in metrics) + " |")

    lines += ["", "### Which harmless edits each metric over-penalises", "",
              "Accuracy for each harmless edit, against all five breaking edits.", "",
              "| Harmless edit | " + " | ".join(LABELS.get(m, m) for m in metrics) + " |",
              "|---|" + "---:|" * len(metrics)]
    for b in BENIGN:
        lines.append(f"| {b} | " + " | ".join(f"{pairwise(scores[m], [b], BREAKING).mean():.3f}" for m in metrics) + " |")

    lines += ["", "## Mean score per edit", "",
              "| Edit | Breaks meaning | " + " | ".join(LABELS.get(m, m) for m in metrics) + " |",
              "|---|---|" + "---:|" * len(metrics)]
    for e in EDITS:
        means = [np.mean([s[e] for s in scores[m].values()]) for m in metrics]
        lines.append(f"| {e} | {'yes' if e in BREAKING else 'no'} | " + " | ".join(f"{v:.3f}" for v in means) + " |")

    text = "\n".join(lines) + "\n"
    (Path(__file__).parent / "results.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
